"""employee_id=delivery: bind new release, source and immutable old packages to evidence."""
import ast,hashlib,json,tarfile
from pathlib import Path
R=Path(__file__).resolve().parents[2];D=R/'delivery';E=D/'evidence/layout-release-0.1.6'
def sha(data):return hashlib.sha256(data).hexdigest()
lock=json.loads((D/'manifest/lock.json').read_text())
assert lock['version']=='0.1.6' and lock['assembly_version']=='0.2.9'
rows=json.loads((R/'integration/evidence/layout-assembled-0.2.9/tested-runtime-hashes.json').read_text())['runtime_files']
with tarfile.open(D/lock['package']['path']) as pkg,tarfile.open(D/lock['sources']['path']) as src:
    manifest=json.load(pkg.extractfile('component-manifest.json'))
    for row in manifest['files']:
        assert sha(pkg.extractfile('payload/'+row['path']).read())==row['sha256'],row['path']
    for row in rows:
        p=row['path']; b=pkg.extractfile('payload/'+p).read()
        assert sha(b)==row['sha256'],p
        if p!='bin/server-ime':assert src.extractfile(p).read()==b,p
    other=json.loads((R/'integration/evidence/apps-assembled-0.2.9/tested-runtime-hashes.json').read_text())['runtime_files']
    for row in other:
        assert sha(pkg.extractfile('payload/'+row['path']).read())==row['sha256'],row['path']
    # root launcher is generated by the included assembly builder; exact text is in that source.
    launcher=pkg.extractfile('payload/bin/server-ime').read()
    builder=src.extractfile('integration/tools/build_product.py').read()
    assert launcher.decode() in [n.value for n in ast.walk(ast.parse(builder)) if isinstance(n, ast.Constant) and isinstance(n.value,str)]
for name,digest in json.loads((E/'historical-hashes.json').read_text()).items():
    assert sha((D/'dist'/name).read_bytes())==digest,name
assert sha((D/lock['package']['path']).read_bytes())==lock['package']['sha256']
assert sha((D/lock['sources']['path']).read_bytes())==lock['sources']['sha256']
print(json.dumps({'employee_id':'delivery','result':'PASS','runtime_files':len(rows),'application_runtime_files':len(other),'payload_files':len(manifest['files']),'source_runtime_match':True,'historical_artifacts_unchanged':True,'application_evidence':['integration/evidence/layout-assembled-0.2.9','integration/evidence/apps-assembled-0.2.9'],'deployment':'NOT_DEPLOYED','windows11':'PENDING_USER_ENVIRONMENT'},indent=2))
